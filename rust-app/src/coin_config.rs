static mut LEDGER_PUBKEY: cx_ecfp_256_public_key_t = cx_ecfp_256_public_key_t {
    curve: 0,
    W_len: 0usize,
    W: [0u8; 65usize],
};

pub fn init_coin_config_pubkey() {
    // SAFETY: Call to Ledger SDK FFI function
    if unsafe {
        cx_ecfp_init_public_key_no_throw(
            CX_CURVE_SECP256K1,
            LEDGER_PUBKEY_RAW.as_ptr(),
            LEDGER_PUBKEY_RAW.len(),
            &raw mut LEDGER_PUBKEY,
        )
    } != 0
    {
        panic!("Error: cx_ecfp_init_public_key_no_throw");
    }
}

pub fn check_coin_configuration_signature(config: &[u8], der: &[u8]) -> bool {
    let mut hash = [0u8; 32];

    // SAFETY: Call to Ledger SDK FFI function
    unsafe {
        cx_hash_sha256(config.as_ptr(), config.len(), hash.as_mut_ptr(), hash.len());
    }

    // SAFETY: Call to Ledger SDK FFI function
    unsafe {
        cx_ecdsa_verify_no_throw(
            &raw const LEDGER_PUBKEY,
            hash.as_ptr(),
            hash.len(),
            der.as_ptr(),
            der.len(),
        )
    }
}
